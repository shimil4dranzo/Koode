/*
 * Koode service worker.
 *
 * Scope, deliberately narrow (Section 7): cache the app shell and static
 * assets so a repeat visit opens instantly on bad mobile data, and show a
 * clear offline page when the network is gone.
 *
 * There is NO offline mutation support. No background sync, no write queue,
 * no optimistic posting. A queued recommendation that syncs three days later
 * — after the subject rejected their claim, or after the job was filled — is
 * worse than an honest "you are offline". Every mutation goes straight to the
 * network and fails visibly.
 *
 * Hand-written rather than generated by Workbox: this is about eighty lines
 * of cache logic, and a generated service worker is the hardest kind of file
 * to debug when it serves a stale shell to every user in town.
 */

const VERSION = 'v1';
const SHELL_CACHE = `koode-shell-${VERSION}`;
const ASSET_CACHE = `koode-assets-${VERSION}`;

const OFFLINE_URL = '/offline.html';

/* Precached at install: enough to render something useful with no network. */
const SHELL_ASSETS = [OFFLINE_URL, '/manifest.webmanifest'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) => cache.addAll(SHELL_ASSETS))
      // Take over as soon as possible; the previous worker is discarded in
      // `activate` below, so there is no half-updated state to worry about.
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('koode-') && !key.endsWith(VERSION))
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

/**
 * Is this a request we may serve from cache?
 *
 * Anything carrying or returning personal data must not be cached, ever. That
 * rules out the whole API, and it rules out cross-origin requests, which the
 * CSP forbids anyway.
 */
function isCacheable(request, url) {
  if (request.method !== 'GET') return false;
  if (url.origin !== self.location.origin) return false;
  if (url.pathname.startsWith('/api/')) return false;
  // A claim link is a secret in a URL and one person's personal data.
  if (url.pathname.includes('/claim/')) return false;
  return true;
}

/** Next's build output is content-hashed, so it can be cached indefinitely. */
function isImmutableAsset(url) {
  return url.pathname.startsWith('/_next/static/') || url.pathname.startsWith('/icons/');
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);

  if (!isCacheable(request, url)) return;

  if (isImmutableAsset(url)) {
    // Cache-first: the filename changes when the content does, so a hit is
    // always correct and saves a round trip on a slow connection.
    event.respondWith(
      caches.match(request).then(
        (cached) =>
          cached ??
          fetch(request).then((response) => {
            if (response.ok) {
              const copy = response.clone();
              caches.open(ASSET_CACHE).then((cache) => cache.put(request, copy));
            }
            return response;
          }),
      ),
    );
    return;
  }

  if (request.mode === 'navigate') {
    // Network-first for pages: job postings and recommendations change, and
    // showing a stale listing would waste somebody's afternoon. The cache is
    // the fallback, not the default.
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(SHELL_CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(async () => {
          const cached = await caches.match(request);
          if (cached) return cached;

          const offline = await caches.match(OFFLINE_URL);
          return (
            offline ??
            new Response('Offline', {
              status: 503,
              headers: { 'Content-Type': 'text/plain; charset=utf-8' },
            })
          );
        }),
    );
  }
});
